GRANT SELECT, INSERT, UPDATE ON REFERENCIA TO ROL_DOCTOR;

GRANT SELECT ON PACIENTE TO ROL_TERAPEUTA;
GRANT SELECT ON EXPEDIENTE TO ROL_TERAPEUTA;
GRANT SELECT ON REFERENCIA TO ROL_TERAPEUTA;

GRANT SELECT, INSERT, UPDATE ON TERAPIA TO ROL_TERAPEUTA;
GRANT SELECT, INSERT, UPDATE ON NOTA_EVOLUCION TO ROL_TERAPEUTA;

