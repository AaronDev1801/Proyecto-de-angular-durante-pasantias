CREATE TABLE PACIENTE (
    CEDULA              VARCHAR2(20 CHAR) PRIMARY KEY,
    NOMBRES             VARCHAR2(100 CHAR) NOT NULL,
    APELLIDOS           VARCHAR2(100 CHAR) NOT NULL,
    SEXO                CHAR(1) CHECK(SEXO IN ('M','F')),
    NACION              VARCHAR2(50 CHAR),
    FECHA_NACIMIENTO    DATE,
    DIRECCION           VARCHAR2(250 CHAR),
    TELEFONO            VARCHAR2(20 CHAR)
);

CREATE TABLE EXPEDIENTE (
    NUMEXP              NUMBER GENERATED ALWAYS AS IDENTITY,
    CEDULA              VARCHAR2(20 CHAR) NOT NULL UNIQUE,
    ESTADO              VARCHAR2(20 CHAR) DEFAULT 'ACTIVO' CHECK(ESTADO IN ('ACTIVO','INACTIVO','CERRADO')),
    FECHA_APERTURA      DATE DEFAULT SYSDATE,
    CONSTRAINT PK_EXPEDIENTE PRIMARY KEY(NUMEXP),
    CONSTRAINT FK_EXPEDIENTE_PACIENTE FOREIGN KEY(CEDULA) REFERENCES PACIENTE(CEDULA)
);

CREATE TABLE PERSONAL_SALUD (
    NUMSAL              NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE              VARCHAR2(100 CHAR) NOT NULL,
    APELLIDO            VARCHAR2(100 CHAR) NOT NULL,
    ESPECIALIDAD        VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_PERSONAL PRIMARY KEY(NUMSAL)
);

CREATE TABLE ADMISION (
    ID_ADMISION         NUMBER GENERATED ALWAYS AS IDENTITY,
    NUMEXP              NUMBER NOT NULL,
    FECHA               DATE DEFAULT SYSDATE,
    MOTIVO              VARCHAR2(500 CHAR),
    HOSPITAL_PROCEDENCIA VARCHAR2(200 CHAR),
    ESTADO              VARCHAR2(20 CHAR) CHECK (ESTADO IN ('PENDIENTE','EN_CONSULTA','CONSULTADO','REFERIDO')),
    NUMSAL              NUMBER NOT NULL,
    USUARIO_CREACION      VARCHAR2(50),
    FECHA_CREACION        DATE DEFAULT SYSDATE,
    USUARIO_MODIFICACION  VARCHAR2(50),
    FECHA_MODIFICACION    DATE,
    CONSTRAINT PK_ADMISION PRIMARY KEY(ID_ADMISION),
    CONSTRAINT FK_ADMISION_EXPEDIENTE FOREIGN KEY(NUMEXP) REFERENCES EXPEDIENTE(NUMEXP),
    CONSTRAINT FK_ADMISION_PERSONAL FOREIGN KEY(NUMSAL) REFERENCES PERSONAL_SALUD(NUMSAL)
);

CREATE TABLE CONSULTA (
    IDCON               NUMBER GENERATED ALWAYS AS IDENTITY,
    ID_ADMISION         NUMBER NOT NULL UNIQUE,
    MOTIVO              VARCHAR2(1000 CHAR),
    SINTOMAS            VARCHAR2(2000 CHAR),
    DIAGNOSTICO         VARCHAR2(2000 CHAR),
    DESTINO             VARCHAR2(500 CHAR),
    FECHA_CONSULTA      DATE DEFAULT SYSDATE,
    NUMSAL              NUMBER NOT NULL,
    USUARIO_CREACION      VARCHAR2(50),
    FECHA_CREACION        DATE DEFAULT SYSDATE,
    USUARIO_MODIFICACION  VARCHAR2(50),
    FECHA_MODIFICACION    DATE,
    CONSTRAINT PK_CONSULTA PRIMARY KEY(IDCON),
    CONSTRAINT FK_CONSULTA_ADMISION FOREIGN KEY(ID_ADMISION) REFERENCES ADMISION(ID_ADMISION),
    CONSTRAINT FK_CONSULTA_PERSONAL FOREIGN KEY(NUMSAL) REFERENCES PERSONAL_SALUD(NUMSAL)
);

CREATE TABLE ESPECIALIDAD (
    IDESP               NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE              VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    CONSTRAINT PK_ESPECIALIDAD PRIMARY KEY(IDESP)
);

CREATE TABLE REFERENCIA (
    IDREF               NUMBER GENERATED ALWAYS AS IDENTITY,
    IDCON               NUMBER NOT NULL UNIQUE,
    FECHA               DATE DEFAULT SYSDATE,
    MOTIVO              VARCHAR2(2000 CHAR),
    PLAN_TRATAMIENTO    VARCHAR2(2000 CHAR),
    IDESP               NUMBER NOT NULL,
    NUMSAL              NUMBER NOT NULL,
    USUARIO_CREACION      VARCHAR2(50),
    FECHA_CREACION        DATE DEFAULT SYSDATE,
    USUARIO_MODIFICACION  VARCHAR2(50),
    FECHA_MODIFICACION    DATE,
    CONSTRAINT PK_REFERENCIA PRIMARY KEY(IDREF),
    CONSTRAINT FK_REFERENCIA_CONSULTA FOREIGN KEY(IDCON) REFERENCES CONSULTA(IDCON),
    CONSTRAINT FK_REFERENCIA_ESPECIALIDAD FOREIGN KEY(IDESP) REFERENCES ESPECIALIDAD(IDESP),
    CONSTRAINT FK_REFERENCIA_PERSONAL FOREIGN KEY(NUMSAL) REFERENCES PERSONAL_SALUD(NUMSAL)
);

CREATE TABLE TERAPIA (
    IDTERA              NUMBER GENERATED ALWAYS AS IDENTITY,
    IDREF               NUMBER NOT NULL UNIQUE,
    TRATAMIENTO         VARCHAR2(2000 CHAR),
    OBSERVACIONES       VARCHAR2(2000 CHAR),
    FECHA               DATE DEFAULT SYSDATE,
    NUMSAL              NUMBER NOT NULL,
    USUARIO_CREACION      VARCHAR2(50),
    FECHA_CREACION        DATE DEFAULT SYSDATE,
    USUARIO_MODIFICACION  VARCHAR2(50),
    FECHA_MODIFICACION    DATE,
    CONSTRAINT PK_TERAPIA PRIMARY KEY(IDTERA),
    CONSTRAINT FK_TERAPIA_REFERENCIA FOREIGN KEY(IDREF) REFERENCES REFERENCIA(IDREF),
    CONSTRAINT FK_TERAPIA_PERSONAL FOREIGN KEY(NUMSAL) REFERENCES PERSONAL_SALUD(NUMSAL)
);

CREATE TABLE NOTA_EVOLUCION (
    IDEVO               NUMBER GENERATED ALWAYS AS IDENTITY,
    IDTERA              NUMBER NOT NULL,
    FECHA               DATE DEFAULT SYSDATE,
    NOTAS               VARCHAR2(4000 CHAR),
    SINTOMAS            VARCHAR2(4000 CHAR),
    NUMSAL              NUMBER NOT NULL,
    USUARIO_CREACION      VARCHAR2(50),
    FECHA_CREACION        DATE DEFAULT SYSDATE,
    USUARIO_MODIFICACION  VARCHAR2(50),
    FECHA_MODIFICACION    DATE,
    CONSTRAINT PK_EVOLUCION PRIMARY KEY(IDEVO),
    CONSTRAINT FK_EVOLUCION_TERAPIA FOREIGN KEY(IDTERA) REFERENCES TERAPIA(IDTERA),
    CONSTRAINT FK_EVOLUCION_PERSONAL FOREIGN KEY(NUMSAL) REFERENCES PERSONAL_SALUD(NUMSAL)
);

CREATE TABLE ROL (
    IDROL NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(50 CHAR) UNIQUE NOT NULL
);

CREATE TABLE USUARIO_SISTEMA (
    IDUSUARIO           NUMBER GENERATED ALWAYS AS IDENTITY,
    USERNAME            VARCHAR2(50 CHAR) UNIQUE NOT NULL,
    PASSWORD_HASH       VARCHAR2(255 CHAR) NOT NULL,
    NUMSAL              NUMBER,
    IDROL               NUMBER NOT NULL,
    ACTIVO              CHAR(1) DEFAULT 'S' CHECK(ACTIVO IN ('S','N')),
    CONSTRAINT PK_USUARIO PRIMARY KEY(IDUSUARIO),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY(IDROL) REFERENCES ROL(IDROL),
    CONSTRAINT FK_USUARIO_PERSONAL FOREIGN KEY(NUMSAL) REFERENCES PERSONAL_SALUD(NUMSAL)
);

